interface LanguageContextValue { language: 'en' | 'he'; setLanguage: (language: 'en' | 'he') => void; t: (text: string) => string; }
const LanguageContext = createContext<LanguageContextValue>({ language: 'en', setLanguage: () => {}, t: text => text });
export const useLanguage = () => useContext(LanguageContext);

export const LanguageProvider = ({ children }: { children: React.ReactNode }) => {
  const [language, setLanguage] = useState<'en' | 'he'>(() => localStorage.getItem('crazyforums-language') === 'he' ? 'he' : 'en');
  useEffect(() => {
    localStorage.setItem('crazyforums-language', language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'he' ? 'rtl' : 'ltr';
  }, [language]);
  useEffect(() => {
    const sync = (event: StorageEvent) => {
      if (event.key === 'crazyforums-language') setLanguage(event.newValue === 'he' ? 'he' : 'en');
    };
    window.addEventListener('storage', sync);
    return () => window.removeEventListener('storage', sync);
  }, []);
  const t = (text: string) => language === 'he'
    ? (/^[\u0590-\u05ff]/.test(text) ? text : (he[text] || text))
    : (/^[\u0590-\u05ff]/.test(text) ? (he[text] || text) : text);
  return <LanguageContext.Provider value={{ language, setLanguage, t }}>
    {children}
    <div className="fixed bottom-4 start-4 z-[70] rounded-md border border-border bg-background/90 p-1 shadow-lg backdrop-blur-md flex items-center gap-1" role="group" aria-label={language === 'he' ? 'שפת האתר' : 'Site language'} dir="ltr">
      <Languages className="w-4 h-4 text-primary mx-1" aria-hidden="true" />
      <Button size="sm" variant={language === 'en' ? 'secondary' : 'ghost'} className="h-7 px-2 text-xs" onClick={() => setLanguage('en')} aria-pressed={language === 'en'}>EN</Button>
      <Button size="sm" variant={language === 'he' ? 'secondary' : 'ghost'} className="h-7 px-2 text-xs" onClick={() => setLanguage('he')} aria-pressed={language === 'he'}>עב</Button>
    </div>
  </LanguageContext.Provider>;
};
